"""Every Docker call in the project goes through here.

One image per target (`rt-target-<name>`) holds the target's pinned Python, system
packages, and a venv at /opt/venv built from the committed `locks/<name>.test-env.txt`.
A run starts a *throwaway* container: the worktree is mounted read-only at /src and
copied to /app, so (a) tests run at native filesystem speed instead of over the
Windows bind mount, and (b) nothing a test or an upgrade does can leak into the next
run. Everything we create carries the label project=reachability-triage.
"""
from __future__ import annotations

import shlex
import subprocess
import sys
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

from .config import LOCKS, ROOT, Target

LABEL = "project=reachability-triage"
UV_IMAGE = "ghcr.io/astral-sh/uv:0.5.31"
DOCKERFILES = ROOT / "docker" / "targets"

_TEMPLATE = """\
# Generated by `rt images` from targets.yaml; edit targets.yaml, not this file.
FROM python:{python}-slim-bookworm
LABEL project=reachability-triage target={name}
RUN apt-get update \\
 && apt-get install -y --no-install-recommends git build-essential {system_packages} \\
 && rm -rf /var/lib/apt/lists/*
COPY --from={uv_image} /uv /usr/local/bin/uv
RUN uv venv /opt/venv -p /usr/local/bin/python
# The exact frozen environment from Phase 0 (runtime + test tooling), installed as-is.
COPY {name}.test-env.txt /tmp/requirements.txt
RUN uv pip install -p /opt/venv/bin/python --no-deps -r /tmp/requirements.txt
ENV PY=/opt/venv/bin/python PATH=/opt/venv/bin:$PATH PYTHONDONTWRITEBYTECODE=1 TZ=UTC
WORKDIR /app
"""


def dockerfile(t: Target) -> Path:
    path = DOCKERFILES / f"{t.name}.Dockerfile"
    path.parent.mkdir(parents=True, exist_ok=True)
    text = _TEMPLATE.format(python=t.python, name=t.name, uv_image=UV_IMAGE,
                            system_packages=" ".join(t.system_packages))
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def build_image(t: Target) -> None:
    df = dockerfile(t)
    cmd = ["docker", "build", "-q", "-t", t.image, "--label", LABEL, "-f", str(df), str(LOCKS)]
    print("+ " + " ".join(cmd), file=sys.stderr)
    subprocess.run(cmd, check=True)


def image_exists(t: Target) -> bool:
    return subprocess.run(["docker", "image", "inspect", t.image], capture_output=True).returncode == 0


@dataclass
class RunResult:
    exit_code: int
    output: str
    seconds: float
    timed_out: bool = False


def run(t: Target, worktree: Path, script: str, timeout: int = 900, network: bool = True) -> RunResult:
    """Run a bash script in a fresh container with the worktree copied to /app."""
    name = f"rt-{t.name}-{uuid.uuid4().hex[:8]}"
    body = "set -o pipefail; cp -a /src/. /app/ && cd /app && " + script
    cmd = ["docker", "run", "--rm", "--name", name, "--label", LABEL,
           "-v", f"{Path(worktree).resolve()}:/src:ro"]
    if not network:
        cmd += ["--network", "none"]
    cmd += [t.image, "bash", "-c", body]
    start = time.monotonic()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace",
                              timeout=timeout)
        return RunResult(proc.returncode, proc.stdout + proc.stderr, round(time.monotonic() - start, 1))
    except subprocess.TimeoutExpired as e:
        subprocess.run(["docker", "kill", name], capture_output=True)
        out = (e.stdout or b"") + (e.stderr or b"")
        out = out.decode("utf-8", "replace") if isinstance(out, bytes) else out
        return RunResult(-1, out, round(time.monotonic() - start, 1), timed_out=True)


def run_tests(t: Target, worktree: Path, test_ids: list[str] | None = None, setup: list[str] | None = None,
              timeout: int = 900) -> RunResult:
    """Run the target's suite (or just `test_ids`) after optional setup commands (e.g. an upgrade).

    `test_ids` are pytest node ids, or dotted test labels for Django's runner.
    """
    cmd = t.test_cmd
    if test_ids:
        ids = " ".join(shlex.quote(i) for i in test_ids)
        if "manage.py test" in cmd:
            cmd = f"$PY manage.py test {ids}"
        else:
            env_prefix = "TZ=UTC " if cmd.startswith("TZ=UTC") else ""
            cmd = f"{env_prefix}$PY -m pytest -p no:randomly -p no:cacheprovider -q {ids}"
    steps = [*(setup or []), cmd]
    return run(t, worktree, " && ".join(f"( {s} )" for s in steps[:-1]) + (" && " if setup else "") + steps[-1],
               timeout=timeout)


def py(t: Target, code: str, timeout: int = 120) -> str:
    """Run a Python snippet in the target image (no worktree needed)."""
    cmd = ["docker", "run", "--rm", "--label", LABEL, "--network", "none", t.image,
           "/opt/venv/bin/python", "-c", code]
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, encoding="utf-8")
    if proc.returncode:
        raise RuntimeError(proc.stderr[-2000:])
    return proc.stdout
